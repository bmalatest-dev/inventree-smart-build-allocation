from .plugin_v041 import SmartBuildAllocationPlugin as SmartBuildAllocationPluginBase


class SmartBuildAllocationPlugin(SmartBuildAllocationPluginBase):
    """v0.2.42: diagnostic-only release to verify the live Python backend and frontend asset."""

    VERSION = "0.2.42"
    BACKEND_FINGERPRINT = "allocation-engine-242"

    def get_ui_panels(self, request, context, **kwargs):
        panels = super().get_ui_panels(request, context, **kwargs)
        for panel in panels:
            panel_context = panel.get("context") or {}
            target_id = panel_context.get("build_id")
            if target_id:
                # This value is generated by the live Python plugin class. The JS
                # intentionally does not contain a fallback backend fingerprint.
                panel_context["backend_fingerprint"] = self.BACKEND_FINGERPRINT
                panel_context["version"] = self.VERSION
                panel["context"] = panel_context
                panel["source"] = self.plugin_static_file("smart_allocation_v042.js:renderPanel")
        return panels
